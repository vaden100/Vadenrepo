#!/usr/bin/env node
/**
 * Bundles long-form Markdown (apps/web/content/legal/*.md) into a generated module, so pages do
 * not read files at runtime (Cloudflare Workers have no filesystem). `--check` fails if stale.
 */
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const dir = path.join(root, 'apps/web/content/legal');
const out = path.join(dir, 'generated.ts');
const docs = Object.fromEntries(
  fs
    .readdirSync(dir)
    .filter((f) => f.endsWith('.md'))
    .sort()
    .map((f) => [f.replace(/\.md$/, ''), fs.readFileSync(path.join(dir, f), 'utf8')]),
);
const ts = `// GENERATED by scripts/sync-content.mjs from content/legal/*.md. Do not edit; run \`pnpm content:sync\`.

export const legalDocs = ${JSON.stringify(docs, null, 2)} as const;

export type LegalDoc = keyof typeof legalDocs;
`;
const prev = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : null;
if (process.argv.includes('--check')) {
  if (prev !== ts) {
    console.error('Content out of date. Run `pnpm content:sync`.');
    process.exit(1);
  }
  console.log('content: up to date');
} else {
  if (prev !== ts) fs.writeFileSync(out, ts);
  console.log('content: synced');
}
