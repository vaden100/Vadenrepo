/**
 * Brand pipeline (SPEC 6.6, 7.1, 7.4). brand/ is the only place SVG masters live.
 *
 * syncBrand():
 *  1. checks every SVG against the rules in SPEC 7.4 and fails on any violation
 *  2. optimizes it with SVGO and writes the optimized master back (check mode: fails instead)
 *  3. generates packages/ui/src/generated/brand.ts (typed: Logo, Icon and Shape read it)
 *  4. copies masters to apps/web/public/brand/ (press kit, external use)
 *  5. writes apps/web/app/icon.svg, the favicon, from brand/logo/mark.svg with token colors
 *
 * Header logo, favicon and social images all come from these outputs, so replacing files in
 * brand/logo/ and running `pnpm brand:sync` swaps the logo everywhere with no code edits.
 */
import fs from 'node:fs';
import path from 'node:path';
import { optimize } from 'svgo';

export const GROUPS = ['logo', 'icons', 'shapes'];
export const REQUIRED_LOGO = ['wordmark', 'wordmark-light', 'mark'];

const FORBIDDEN = [
  [/<script\b/i, 'script'],
  [/<foreignObject\b/i, 'foreignObject'],
  [/<image\b/i, 'embedded image'],
  [/<(animate|animateMotion|animateTransform|set)\b/i, 'SMIL animation'],
  [/\son[a-z]+\s*=/i, 'event handler attribute'],
  [/(xlink:)?href\s*=\s*"(?!#)/i, 'external reference'],
  [/url\((?!#)/i, 'external url()'],
  [/<style\b/i, 'style element (use attributes and currentColor)'],
];

const svgoConfig = {
  multipass: true,
  floatPrecision: 1,
  plugins: [
    { name: 'preset-default' },
    'removeDimensions',
    { name: 'removeAttrs', params: { attrs: ['class', 'data-.*'] } },
  ],
};

/** Returns a list of rule violations for one SVG source. */
export function lint(src, file) {
  const problems = [];
  const root = /<svg\b[^>]*>/i.exec(src)?.[0] ?? '';
  if (!root) problems.push('no <svg> root');
  if (!/\sviewBox="/.test(root)) problems.push('missing viewBox');
  if (/\s(width|height)="/.test(root)) problems.push('fixed width/height on <svg>');
  for (const [re, what] of FORBIDDEN) if (re.test(src)) problems.push(what);
  // Colors come from currentColor. Only the "-light" logo for dark backgrounds may pin white.
  const colors = [...src.matchAll(/(?:fill|stroke)="(#[0-9a-f]{3,8}|rgb[^"]*|[a-z]+)"/gi)]
    .map((m) => m[1].toLowerCase())
    .filter((c) => !['none', 'currentcolor'].includes(c));
  const allowed = file.endsWith('-light.svg') ? ['#fff', '#ffffff'] : [];
  for (const c of colors) if (!allowed.includes(c)) problems.push(`hard-coded color ${c}`);
  return problems;
}

const list = (dir) =>
  fs.existsSync(dir)
    ? fs
        .readdirSync(dir)
        .filter((f) => f.endsWith('.svg'))
        .sort()
    : [];

/** viewBox and inner markup, minus <title> (components supply the accessible name). */
export function parts(svg) {
  const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1] ?? '0 0 24 24';
  const rootAttrs = /<svg\b([^>]*)>/.exec(svg)?.[1] ?? '';
  const attrs = Object.fromEntries(
    [...rootAttrs.matchAll(/([a-z-]+)="([^"]*)"/gi)]
      .filter(([, k]) => !['xmlns', 'viewBox'].includes(k))
      .map(([, k, v]) => [k, v]),
  );
  const body = svg
    .replace(/^[\s\S]*?<svg\b[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/<title>[\s\S]*?<\/title>/g, '');
  return { viewBox, attrs, body };
}

export function syncBrand({ root, brandDir = path.join(root, 'brand'), check = false, colors }) {
  const stale = [];
  const errors = [];
  const write = (file, content) => {
    const prev = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
    if (prev === content) return;
    if (check) return stale.push(path.relative(root, file));
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content);
  };

  const assets = {};
  for (const group of GROUPS) {
    assets[group] = {};
    for (const f of list(path.join(brandDir, group))) {
      const file = path.join(brandDir, group, f);
      const src = fs.readFileSync(file, 'utf8');
      const rel = `brand/${group}/${f}`;
      for (const p of lint(src, f)) errors.push(`${rel}: ${p}`);
      const optimized = optimize(src, { ...svgoConfig, path: file }).data + '\n';
      if (optimized !== src) {
        if (check) stale.push(`${rel} (not optimized)`);
        else fs.writeFileSync(file, optimized);
      }
      assets[group][f.replace(/\.svg$/, '')] = parts(optimized);
      write(path.join(root, 'apps/web/public/brand', group, f), optimized);
    }
  }
  for (const name of REQUIRED_LOGO)
    if (!assets.logo[name]) errors.push(`brand/logo/${name}.svg is missing`);

  if (errors.length) return { ok: false, errors, stale };

  const ts = `// GENERATED by scripts/sync-brand.mjs from brand/. Do not edit; run \`pnpm brand:sync\`.

export interface BrandSvg {
  viewBox: string;
  /** Root attributes other than viewBox (fill, stroke...). */
  attrs: Record<string, string>;
  /** Inner markup, optimized and checked against SPEC 7.4. */
  body: string;
}

export const logos = ${JSON.stringify(assets.logo, null, 2)} as const satisfies Record<string, BrandSvg>;
export const icons = ${JSON.stringify(assets.icons, null, 2)} as const satisfies Record<string, BrandSvg>;
export const shapes = ${JSON.stringify(assets.shapes, null, 2)} as const satisfies Record<string, BrandSvg>;

export type LogoName = keyof typeof logos;
export type IconName = keyof typeof icons;
export type ShapeName = keyof typeof shapes;
`;
  write(path.join(root, 'packages/ui/src/generated/brand.ts'), ts);

  // Favicon: the mark in ink color, switching for dark browser chrome.
  const mark = assets.logo.mark;
  const favicon =
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${mark.viewBox}">` +
    `<style>*{fill:${colors.light}}@media (prefers-color-scheme:dark){*{fill:${colors.dark}}}</style>` +
    mark.body.replace(/\s*fill="currentColor"/g, '') +
    `</svg>\n`;
  write(path.join(root, 'apps/web/app/icon.svg'), favicon);

  return { ok: true, errors, stale };
}
